import test from "node:test";
import assert from "node:assert/strict";
import {
  validateAddress, encodeAddress, decodeAddress, getNetwork, bytesToHex, namehash, normalizeName,
  base58CheckEncode, hexToBytes, concat, NETWORKS, isMultiNetworkAsset, quote, skeleton,
  findLookalikes, parseUnits, formatUnits, paymentUri, getAsset,
} from "../src/index.ts";
import { getAddress } from "ethers";

const net = (id: string) => getNetwork(id)!;

test("names normalize and reject unicode / bad shapes", () => {
  assert.equal(normalizeName(" Heelo.ADDR "), "heelo.addr");
  for (const bad of ["heelo", "héllo.addr", "a..addr", "-a.addr", "a-.addr", "a--b.addr", "x.eth", ".addr", "a b.addr"]) {
    assert.throws(() => normalizeName(bad), Error, bad);
  }
  assert.equal(namehash("addr".length ? "a.addr" : ""), namehash("a.addr"));
  assert.notEqual(namehash("a.addr"), namehash("b.addr"));
});

test("BTC vectors (BIP-173 / BIP-350 / genesis)", () => {
  const btc = net("bitcoin");
  assert.equal(bytesToHex(encodeAddress(btc, "1A1zP1eP5QGefi2DMPTfTL5SLmv7DivfNa")), "0x76a91462e907b15cbf27d5425399ebf6f0fb50ebb88f1888ac");
  assert.equal(bytesToHex(encodeAddress(btc, "bc1qw508d6qejxtdg4y5r3zarvary0c5xw7kv8f3t4")), "0x0014751e76e8199196d454941c45d1b3a323f1433bd6");
  assert.equal(
    bytesToHex(encodeAddress(btc, "bc1p0xlxvlhemja6c4dqv22uapctqupfhlxm9h8z3k2e72q4k9hcz7vqzk5jj0")),
    "0x512079be667ef9dcbbac55a06295ce870b07029bfcdb2dce28d959f2815b16f81798",
  );
  // round trip
  for (const a of ["1A1zP1eP5QGefi2DMPTfTL5SLmv7DivfNa", "3J98t1WpEZ73CNmQviecrnyiWrnqRhWNLy", "bc1qw508d6qejxtdg4y5r3zarvary0c5xw7kv8f3t4", "bc1p0xlxvlhemja6c4dqv22uapctqupfhlxm9h8z3k2e72q4k9hcz7vqzk5jj0"]) {
    assert.equal(decodeAddress(btc, encodeAddress(btc, a)), a);
    assert.equal(validateAddress("bitcoin", a).valid, true);
  }
  // invalid
  assert.equal(validateAddress("bitcoin", "1A1zP1eP5QGefi2DMPTfTL5SLmv7DivfNb").valid, false); // checksum
  assert.equal(validateAddress("bitcoin", "bc1qw508d6qejxtdg4y5r3zarvary0c5xw7kv8f3t5").valid, false);
  assert.equal(validateAddress("bitcoin", "tb1qw508d6qejxtdg4y5r3zarvary0c5xw7kxpjzsx").valid, false); // testnet
  assert.equal(validateAddress("bitcoin", "BC1QW508D6QEJXTDG4Y5R3ZARVARY0C5XW7KV8F3T4").valid, true); // uppercase allowed
  assert.equal(validateAddress("bitcoin", "bc1pw508d6qejxtdg4y5r3zarvary0c5xw7kw508d6qejxtdg4y5r3zarvary0c5sw4mq6").valid, false); // v1 with bech32 (BIP-350 invalid)
  assert.equal(validateAddress("bitcoin", " 1A1zP1eP5QGefi2DMPTfTL5SLmv7DivfNa").valid, false);
});

test("LTC encodes with its own prefixes and rejects BTC addresses", () => {
  const ltc = net("litecoin");
  const hash = hexToBytes("0x" + "11".repeat(20));
  const p2pkh = base58CheckEncode(concat(Uint8Array.of(0x30), hash));
  const p2sh = base58CheckEncode(concat(Uint8Array.of(0x32), hash));
  assert.ok(p2pkh.startsWith("L") && p2sh.startsWith("M"));
  assert.equal(decodeAddress(ltc, encodeAddress(ltc, p2pkh)), p2pkh);
  assert.equal(decodeAddress(ltc, encodeAddress(ltc, p2sh)), p2sh);
  // a segwit address generated by our own encoder must round-trip and be rejected on BTC
  const script = hexToBytes("0x0014" + "22".repeat(20));
  const bech = decodeAddress(ltc, script);
  assert.ok(bech.startsWith("ltc1q"));
  assert.equal(validateAddress("litecoin", bech).valid, true);
  assert.equal(validateAddress("bitcoin", bech).valid, false);
  assert.equal(validateAddress("litecoin", "1A1zP1eP5QGefi2DMPTfTL5SLmv7DivfNa").valid, false);
});

test("EVM checksum enforcement", () => {
  const good = getAddress("0xdac17f958d2ee523a2206206994597c13d831ec7");
  assert.equal(validateAddress("ethereum", good).valid, true);
  assert.equal(validateAddress("base", good.toLowerCase()).valid, true); // all-lowercase has no checksum to violate
  const i = good.slice(2).search(/[a-fA-F]/) + 2;
  const broken = good.slice(0, i) + (good[i] === good[i].toUpperCase() ? good[i].toLowerCase() : good[i].toUpperCase()) + good.slice(i + 1);
  assert.equal(validateAddress("ethereum", broken).valid, false);
  assert.equal(validateAddress("ethereum", "0x1234").valid, false);
});

test("Solana and TRON", () => {
  assert.equal(validateAddress("solana", "11111111111111111111111111111111").valid, true);
  assert.equal(validateAddress("solana", "Es9vMFrzaCERmJfrF4H2FYD4KCoNkY11McCe8BenwNYB").valid, true);
  assert.equal(validateAddress("solana", "Es9vMFrzaCERmJfrF4H2FYD4KCoNkY11McCe8BenwNYBB").valid, false);
  assert.equal(validateAddress("solana", "0OIl").valid, false);
  const tusdt = net("tron").assets.find((a) => a.symbol === "USDT")!.contract!;
  assert.equal(validateAddress("tron", tusdt).valid, true);
  assert.equal(validateAddress("tron", tusdt.slice(0, -1) + "k").valid, false);
  assert.equal(validateAddress("tron", "1A1zP1eP5QGefi2DMPTfTL5SLmv7DivfNa").valid, false);
  assert.equal(bytesToHex(encodeAddress(net("tron"), tusdt)).length, 2 + 42);
});

test("every configured token contract is a valid address on its own network", () => {
  for (const n of NETWORKS) {
    for (const a of n.assets) {
      if (a.contract) assert.equal(validateAddress(n.id, a.contract).valid, true, `${n.id} ${a.symbol} ${a.contract}`);
    }
  }
});

test("USDT/USDC are multi-network and must be network-qualified", () => {
  assert.equal(isMultiNetworkAsset("USDT"), true);
  assert.equal(isMultiNetworkAsset("BTC"), false);
  assert.ok(getAsset(net("tron"), "usdt", "trc20"));
  assert.equal(getAsset(net("tron"), "usdt", "erc20"), undefined);
});

test("pricing policy", () => {
  assert.equal(quote("heelo", 1, false).free, true);
  assert.equal(quote("heelo", 1, true).totalUsdMicro, 5_000_000);
  assert.equal(quote("abcd", 2, false).totalUsdMicro, 30_000_000);
  assert.equal(quote("lee", 1, false).totalUsdMicro, 50_000_000);
  assert.equal(quote("ab", 1, false).totalUsdMicro, 200_000_000);
  assert.equal(quote("a", 1, false).available, false);
});

test("lookalikes", () => {
  assert.equal(skeleton("paypa1"), skeleton("paypal"));
  assert.equal(skeleton("rnicrosoft"), skeleton("microsoft"));
  const l = findLookalikes("paypa1", ["paypal", "other", "paypa1"]);
  assert.deepEqual(l, [{ name: "paypal", reason: "confusable" }]);
  assert.equal(findLookalikes("coinbasf", ["coinbase"])[0].reason, "near-typo");
});

test("units and URIs", () => {
  assert.equal(parseUnits("1.5", 6), 1500000n);
  assert.equal(formatUnits(1500000n, 6), "1.5");
  assert.throws(() => parseUnits("1.1234567", 6));
  const sol = net("solana");
  assert.equal(paymentUri(sol, getAsset(sol, "USDC")!, "11111111111111111111111111111111", "2"),
    "solana:11111111111111111111111111111111?amount=2&spl-token=EPjFWdd5AufqSSqeM2qN1xzybapC8G4wEGGkZwyTDt1v");
  const eth = net("ethereum");
  assert.ok(paymentUri(eth, getAsset(eth, "ETH")!, getAddress("0x" + "11".repeat(20)), "1").endsWith("@1?value=1000000000000000000"));
});
