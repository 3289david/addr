// Generates packages/core/src/abi.ts (human-readable ABIs + bytecode-free) from compiled artifacts.
const fs = require("fs");
const path = require("path");
const { Interface } = require("ethers");

const root = path.join(__dirname, "..");
const out = [];
for (const [name, file] of [
  ["registry", "AddrRegistry"],
  ["resolver", "AddrResolver"],
  ["registrar", "AddrRegistrar"],
]) {
  const art = JSON.parse(fs.readFileSync(path.join(root, "artifacts/contracts", file + ".sol", file + ".json"), "utf8"));
  const iface = new Interface(art.abi);
  const frags = iface.format(false); // full signatures
  out.push(`export const ${name}Abi = ${JSON.stringify(frags, null, 2)} as const;`);
}
out.push(
  `export const erc20Abi = [
  "function balanceOf(address) view returns (uint256)",
  "function decimals() view returns (uint8)",
  "function allowance(address,address) view returns (uint256)",
  "function approve(address,uint256) returns (bool)",
  "function transfer(address,uint256) returns (bool)",
  "event Transfer(address indexed from, address indexed to, uint256 value)"
] as const;`,
);
fs.writeFileSync(path.join(root, "packages/core/src/abi.ts"), "// GENERATED by scripts/build-abi.cjs - do not edit\n" + out.join("\n\n") + "\n");
console.log("abi.ts written");
